// parseGlyph turns 7 or 8 rows of 5-wide art into a tile, one pixel in from
// the left so a shadow and bold strike still fit inside 8 pixels.
func parseGlyph(art string) (glyph, error) {
	var g glyph
	rows := strings.Fields(art)
	if len(rows) < 7 || len(rows) > Tile {
		return g, fmt.Errorf("want 7 or 8 rows, got %d", len(rows))
	}
	for y, row := range rows {
		if len(row) != 5 {
			return g, fmt.Errorf("row %d is %d wide, want 5", y, len(row))
		}
		for x, c := range row {
			switch c {
			case '#':
				g[y] |= 0x80 >> (x + 1)
			case '.':
			default:
				return g, fmt.Errorf("row %d: bad char %q", y, c)
			}
		}
	}
	return g, nil
}

var font = func() map[rune]glyph {
	m := make(map[rune]glyph, len(fontArt))
	for r, art := range fontArt {
		g, err := parseGlyph(art)
		if err != nil {
			// The art is a compile-time constant; TestFontArtWellFormed
			// catches this before it can ship.
			panic(fmt.Sprintf("font glyph %q: %v", r, err))
		}
		m[r] = g
	}
	return m
}()

// Supported reports whether r can be drawn in graphics mode, either from the
// font or by one of the procedural shapes.
func Supported(r rune) bool {
	if _, ok := font[r]; ok {
		return true
	}
	_, ok := shape(r)
	return ok
}
